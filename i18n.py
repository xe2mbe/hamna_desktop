_current_lang: str = "es"


def set_language(lang: str) -> None:
    """Set the active language. Falls back to 'es' if unknown."""
    global _current_lang
    if lang in _STRINGS:
        _current_lang = lang


def get_language() -> str:
    return _current_lang


def t(key: str) -> str:
    """Return the translated string for *key* in the current language."""
    lang_dict = _STRINGS.get(_current_lang, _STRINGS["es"])
    if key in lang_dict:
        return lang_dict[key]
    # Fallback to Spanish
    return _STRINGS["es"].get(key, key)
